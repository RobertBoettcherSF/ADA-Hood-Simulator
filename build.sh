#!/bin/sh
# Builds dist/index.html and dist/version.txt.
# The Ada core (src/, src/wasm/) is compiled to WebAssembly with AdaWebPack 24
# (GNAT-LLVM), linked with wasm-ld and inlined as base64 into web/template.html.
# Wasm builds use -gnatp; the contracts are checked by the native smoke test
# (tests/smoke.gpr, -gnata). This script never downloads anything: the
# toolchain comes from $ADAWEBPACK (default ~/toolchains/adawebpack-24),
# installed once with tools/get-toolchain.sh.
set -e
cd "$(dirname "$0")"

VERSION=0.2.0   # proposed

A=${ADAWEBPACK:-$HOME/toolchains/adawebpack-24}
T=$A/usr
if [ ! -x "$T/bin/llvm-gcc" ]; then
  echo "AdaWebPack 24 not found in $A."
  echo "Set ADAWEBPACK to its folder, or run tools/get-toolchain.sh once (about 58 MB download)."
  exit 1
fi
export LD_LIBRARY_PATH="$A/lib${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"

if command -v wasm-ld > /dev/null; then
  LD=wasm-ld
elif ls /usr/bin/wasm-ld-* > /dev/null 2>&1; then
  LD=$(ls /usr/bin/wasm-ld-* | tail -1)
elif python3 -c "import ziglang" 2> /dev/null; then
  LD="python3 -m ziglang wasm-ld"
else
  echo "wasm-ld not found: install lld (sudo apt install lld)."
  exit 1
fi

# Stamp (D-005): vMAJOR.MINOR.PATCH bYYYYMMDD-HHMM <sha>, Europe/Berlin time,
# trailing + when the source tree differs from the commit.
NOW=$(date +%s)
WHEN=$(TZ=Europe/Berlin date -d "@$NOW" +%Y%m%d-%H%M)
BUILD_ID=$(TZ=Europe/Berlin date -d "@$NOW" +%y%j%H%M)   # YYDDDHHMM, proposed
SHA=$(git rev-parse --short HEAD 2> /dev/null || echo nogit)
[ -z "$(git status --porcelain -- . ':!dist' 2> /dev/null)" ] || SHA="$SHA+"
STAMP="v$VERSION b$WHEN $SHA"

MAJOR=${VERSION%%.*}; REST=${VERSION#*.}; MINOR=${REST%%.*}; PATCH=${REST#*.}
mkdir -p obj/gen obj/wasm dist
cat > obj/gen/hood-version.ads << ADA
--  Generated by build.sh; do not edit.
package Hood.Version with Pure is
   Major    : constant := $MAJOR;
   Minor    : constant := $MINOR;
   Patch    : constant := $PATCH;
   Build_Id : constant := $BUILD_ID;
   Stamp    : constant String := "$STAMP";
end Hood.Version;
ADA

cd obj/wasm
rm -f ./*.o ./*.ali
for F in ../../src/*.adb ../../src/wasm/*.adb; do
  "$T/bin/llvm-gcc" -c --target=wasm32 -O2 -gnat2022 -gnatp -gnatwa -gnatwe \
    --RTS="$T/lib/rts-native" -I../../src -I../../src/wasm -I../gen "$F"
done
# memcpy/memmove/memset come from the Ada runtime library (D-006)
ar x "$T/lib/rts-native/adalib/libgnat.a" s-memcop.o s-memmov.o s-memset.o
# hs_host_error is the only import; it comes from the host (web/template.html)
$LD --no-entry --allow-undefined --strip-all \
  --export=hs_build_id --export=hs_state_hash --export=hs_crash_test \
  --export=hs_error_file_length --export=hs_error_file_char \
  --export=hs_new_game --export=hs_rng_value --export=hs_grid_w --export=hs_grid_h \
  --export=hs_cell_kind --export=hs_check_value \
  -z stack-size=1048576 --initial-memory=33554432 \
  -o hood.wasm ./*.o
cd ../..

STAMP="$STAMP" python3 - << 'PY'
import base64, os
from pathlib import Path
wasm = Path("obj/wasm/hood.wasm").read_bytes()
stamp = os.environ["STAMP"]
html = Path("web/template.html").read_text()
html = html.replace("__WASM_BASE64__", base64.b64encode(wasm).decode("ascii"))
html = html.replace("__STAMP__", stamp)
if "__WASM_BASE64__" in html or "__STAMP__" in html:
    raise SystemExit("template placeholders left unreplaced")
Path("dist/index.html").write_text(html)
Path("dist/version.txt").write_text(stamp + "\n")
print(f"Built dist/index.html ({len(wasm)} bytes of WebAssembly), {stamp}")
PY
