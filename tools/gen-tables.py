#!/usr/bin/env python3
"""Writes src/hood-tables.ads from data/tables.json (building types, business
kinds, trades, block modules and module families), and web/src/tables.ts
with the names the page shows. Run from the repo root:
    python3 tools/gen-tables.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
data = json.loads((ROOT / "data/tables.json").read_text(encoding="utf-8"))

ADA_RESERVED = {"abort", "abs", "abstract", "accept", "access", "aliased", "all", "and", "array", "at",
                "begin", "body", "case", "constant", "declare", "delay", "delta", "digits", "do", "else",
                "elsif", "end", "entry", "exception", "exit", "for", "function", "generic", "goto", "if",
                "in", "interface", "is", "limited", "loop", "mod", "new", "not", "null", "of", "or",
                "others", "out", "overriding", "package", "pragma", "private", "procedure", "protected",
                "raise", "range", "record", "rem", "renames", "requeue", "return", "reverse", "select",
                "separate", "some", "subtype", "synchronized", "tagged", "task", "terminate", "then",
                "type", "until", "use", "when", "while", "with", "xor"}


def ada_name(camel: str) -> str:
    parts = re.findall(r"[A-Z]?[a-z]+|[A-Z]+(?![a-z])|[0-9]+", camel)
    return "_".join(p[:1].upper() + p[1:].lower() for p in parts)


def wrap(items, indent=6, width=78):
    lines, line = [], " " * indent
    for i, item in enumerate(items):
        piece = item + ("," if i < len(items) - 1 else "")
        if len(line) + len(piece) + 1 > width and line.strip():
            lines.append(line.rstrip())
            line = " " * indent
        line += piece + " "
    lines.append(line.rstrip())
    return "\n".join(lines)


types = data["types"]
type_ids = [t["id"] for t in types]
EMPTY = len(types)
tindex = {t: i for i, t in enumerate(type_ids)}
tindex["emptyLand"] = EMPTY
CLASSES = ["empty", "residential", "tenement", "commercial", "industrial", "municipal", "charity", "illegal"]
USES = ["homes", "shops", "business", "works"]
FACINGS = ["north", "east", "south", "west"]
assert data["districts"] == ["downtown", "commercial", "industrial", "residential", "civic"]

out = []
w = out.append
w("--  Generated by tools/gen-tables.py from data/tables.json; do not edit.")
w("--  Building types, business kinds, trades and block modules.")
w("with Interfaces;")
w("")
w("package Hood.Tables with Pure is")
w("")
w("   use Interfaces;")
w("")
w("   type District is (Downtown, Commercial, Industrial, Residential, Civic);")
w("   type Building_Class is")
w("     (" + ", ".join(ada_name(c) for c in CLASSES) + ");")
w("   type Plot_Use is (" + ", ".join(ada_name(u) for u in USES) + ");")
w("   type Facing is (" + ", ".join(ada_name(f) for f in FACINGS) + ");")
w("")
w(f"   Type_Count : constant := {len(types)};")
w(f"   Empty_Land : constant := {EMPTY};  --  the empty-land placeholder, outside the table")
w("   subtype Type_Id is Integer_32 range 0 .. Empty_Land;")
w("   subtype Listed_Type is Type_Id range 0 .. Type_Count - 1;")
w("")
names = set()
for i, t in enumerate(type_ids):
    n = "T_" + ada_name(t)
    assert n not in names, n
    names.add(n)
    w(f"   {n} : constant := {i};")
w("")
w("   Type_Class : constant array (Type_Id) of Building_Class :=")
w("     [" + wrap([ada_name(t["cls"]) for t in types] + ["Empty"], 6).lstrip() + "];")
w("")
w("   No_Weight : constant := -1;  --  no weight given for the district")
w("   type Weight_Row is array (District) of Integer_32;")
w("   Type_Weight : constant array (Listed_Type) of Weight_Row :=")
rows = []
for t in types:
    rows.append("[" + ", ".join(str(x if x is not None else -1) for x in t["weight"]) + "]")
w("     [" + wrap(rows, 6).lstrip() + "];")
w("")
w("   Type_Recruits : constant array (Type_Id) of Boolean :=")
w("     [" + wrap(["True" if t["recruit"] else "False" for t in types] + ["False"], 6).lstrip() + "];")
w("   Type_Special : constant array (Type_Id) of Boolean :=")
w("     [" + wrap(["True" if t["special"] else "False" for t in types] + ["False"], 6).lstrip() + "];")
w("   Type_Storeys : constant array (Type_Id) of Integer_32 :=")
w("     [" + wrap([str(int(t["storeys"])) for t in types] + ["0"], 6).lstrip() + "];")
w("")
kinds = data["kinds"]
w(f"   Kind_Count : constant := {len(kinds)};")
w("   subtype Kind_Id is Integer_32 range 0 .. Kind_Count - 1;")
w("   No_Kind : constant := -1;")
for field, name in [("group", "Kind_Group"), ("capacity", "Kind_Capacity"), ("capacity_max", "Kind_Capacity_Max"),
                    ("lv_min", "Kind_Lv_Min"), ("lv_max", "Kind_Lv_Max"), ("size", "Kind_Size")]:
    w(f"   {name} : constant array (Kind_Id) of Integer_32 :=")
    w("     [" + wrap([str(int(k[field])) for k in kinds], 6).lstrip() + "];")
w("   Kind_Type : constant array (Kind_Id) of Type_Id :=")
w("     [" + wrap([str(tindex[k["type"]]) for k in kinds], 6).lstrip() + "];")
g = data["kind_groups"]
w("   Group_Start : constant array (Integer_32 range 0 .. 7) of Integer_32 :=")
w("     [" + ", ".join(str(x) for x in g["start"]) + "];")
w("   Group_Count : constant array (Integer_32 range 0 .. 7) of Integer_32 :=")
w("     [" + ", ".join(str(x) for x in g["count"]) + "];")
w("")
trades = data["trades"]
w(f"   Trade_Count : constant := {len(trades)};")
w("   subtype Trade_Id is Integer_32 range 0 .. Trade_Count - 1;")
w("   Trade_Type : constant array (Trade_Id) of Listed_Type :=")
w("     [" + wrap([str(tindex[t["id"]]) for t in trades], 6).lstrip() + "];")
w("   Trade_Family : constant array (Trade_Id) of Plot_Use :=")
w("     [" + wrap([ada_name(t["family"]) for t in trades], 6).lstrip() + "];")
w("   Trade_Upmarket : constant array (Trade_Id) of Boolean :=")
w("     [" + wrap(["True" if t["upmarket"] else "False" for t in trades], 6).lstrip() + "];")
w("")
mods = data["modules"]
plots = [p for m in mods for p in m["plots"]]
for p in plots:
    for k in ("x", "y", "w", "h"):
        assert p[k] == int(p[k]), p
w(f"   Module_Count : constant := {len(mods)};")
w("   subtype Module_Id is Integer_32 range 0 .. Module_Count - 1;")
for i, m in enumerate(mods):
    w(f"   M_{'_'.join(x.capitalize() for x in m['id'].split('-'))} : constant := {i};")
w("   Module_Width : constant array (Module_Id) of Integer_32 :=")
w("     [" + ", ".join(str(m["width"]) for m in mods) + "];")
w("   Module_Depth : constant array (Module_Id) of Integer_32 :=")
w("     [" + ", ".join(str(m["depth"]) for m in mods) + "];")
first, k = [], 0
for m in mods:
    first.append(k)
    k += len(m["plots"])
w("   Plot_First : constant array (Module_Id) of Integer_32 :=")
w("     [" + ", ".join(str(x) for x in first) + "];")
w("   Plot_Count : constant array (Module_Id) of Integer_32 :=")
w("     [" + ", ".join(str(len(m["plots"])) for m in mods) + "];")
w(f"   Plot_Total : constant := {len(plots)};")
w("   subtype Plot_Id is Integer_32 range 0 .. Plot_Total - 1;")
w("   type Plot is record")
w("      Index, X, Y, W, H : Integer_32;")
w("      Face              : Facing;")
w("      Use_Kind          : Plot_Use;")
w("      Vacant            : Boolean;")
w("   end record;")
w("   Plots : constant array (Plot_Id) of Plot :=")
prow = [f"({p['index']}, {int(p['x'])}, {int(p['y'])}, {int(p['w'])}, {int(p['h'])}, "
        f"{ada_name(p['facing'])}, {ada_name(p['use'])}, {'True' if p['vacant'] else 'False'})" for p in plots]
w("     [" + wrap(prow, 6).lstrip() + "];")
w("")
fam = data["families"]
ffirst, flist = [], []
for u in USES:
    ffirst.append(len(flist))
    flist += [tindex[t] for t in fam[u]]
w("   Family_First : constant array (Plot_Use) of Integer_32 :=")
w("     [" + ", ".join(str(x) for x in ffirst) + "];")
w("   Family_Length : constant array (Plot_Use) of Integer_32 :=")
w("     [" + ", ".join(str(len(fam[u])) for u in USES) + "];")
w(f"   Family_Total : constant := {len(flist)};")
w("   Family_Types : constant array (Integer_32 range 0 .. Family_Total - 1) of Listed_Type :=")
w("     [" + wrap([str(x) for x in flist], 6).lstrip() + "];")
w("")
w("end Hood.Tables;")
(ROOT / "src/hood-tables.ads").write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"src/hood-tables.ads: {len(types)} types, {len(kinds)} kinds, {len(trades)} trades, "
      f"{len(mods)} modules, {len(plots)} plots")

# The page's copy: type names, classes and storeys by type number (the last
# number is empty land), and the place names.
ts = ["// Generated by tools/gen-tables.py from data/tables.json; do not edit.", ""]
ts.append("export const TYPE_NAMES: readonly string[] = " + json.dumps([t["name"] for t in types] + ["Empty land"], ensure_ascii=False) + ";")
ts.append("export const TYPE_IDS: readonly string[] = " + json.dumps([t["id"] for t in types] + ["emptyLand"]) + ";")
ts.append("export const PARK_NAMES: readonly string[] = " + json.dumps(data["names"]["parks"], ensure_ascii=False) + ";")
ts.append("export const CHURCH_NAMES: readonly string[] = " + json.dumps(data["names"]["churches"], ensure_ascii=False) + ";")
ts.append("export const STREETS_NS: readonly string[] = " + json.dumps(data["names"]["streets_ns"], ensure_ascii=False) + ";")
ts.append("export const STREETS_EW: readonly string[] = " + json.dumps(data["names"]["streets_ew"], ensure_ascii=False) + ";")
(ROOT / "web/src/tables.ts").write_text("\n".join(ts) + "\n", encoding="utf-8")
print(f"web/src/tables.ts: {len(types) + 1} type names")
