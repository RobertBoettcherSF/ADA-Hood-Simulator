#!/usr/bin/env python3
"""Writes src/hood-tables.ads from data/tables.json (building types, business
kinds, trades, block modules and module families), and web/src/tables.ts
with the names the page shows. Run from the repo root:
    python3 tools/gen-tables.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
data = json.loads((ROOT / "data/tables.json").read_text(encoding="utf-8"))

ADA_RESERVED = {"abort", "abs", "abstract", "accept", "access", "aliased", "all", "and", "array", "at",
                "begin", "body", "case", "constant", "declare", "delay", "delta", "digits", "do", "else",
                "elsif", "end", "entry", "exception", "exit", "for", "function", "generic", "goto", "if",
                "in", "interface", "is", "limited", "loop", "mod", "new", "not", "null", "of", "or",
                "others", "out", "overriding", "package", "pragma", "private", "procedure", "protected",
                "raise", "range", "record", "rem", "renames", "requeue", "return", "reverse", "select",
                "separate", "some", "subtype", "synchronized", "tagged", "task", "terminate", "then",
                "type", "until", "use", "when", "while", "with", "xor"}


def ada_name(camel: str) -> str:
    parts = re.findall(r"[A-Z]?[a-z]+|[A-Z]+(?![a-z])|[0-9]+", camel)
    return "_".join(p[:1].upper() + p[1:].lower() for p in parts)


def wrap(items, indent=6, width=78):
    lines, line = [], " " * indent
    for i, item in enumerate(items):
        piece = item + ("," if i < len(items) - 1 else "")
        if len(line) + len(piece) + 1 > width and line.strip():
            lines.append(line.rstrip())
            line = " " * indent
        line += piece + " "
    lines.append(line.rstrip())
    return "\n".join(lines)


types = data["types"]
type_ids = [t["id"] for t in types]
EMPTY = len(types)
tindex = {t: i for i, t in enumerate(type_ids)}
tindex["emptyLand"] = EMPTY
CLASSES = ["empty", "residential", "tenement", "commercial", "industrial", "municipal", "charity", "illegal"]
USES = ["homes", "shops", "business", "works"]
FACINGS = ["north", "east", "south", "west"]
assert data["districts"] == ["downtown", "commercial", "industrial", "residential", "civic"]

out = []
w = out.append
w("--  Generated by tools/gen-tables.py from data/tables.json; do not edit.")
w("--  Building types, business kinds, trades and block modules.")
w("with Interfaces;")
w("")
w("package Hood.Tables with Pure is")
w("")
w("   use Interfaces;")
w("")
w("   type District is (Downtown, Commercial, Industrial, Residential, Civic);")
w("   type Building_Class is")
w("     (" + ", ".join(ada_name(c) for c in CLASSES) + ");")
w("   type Plot_Use is (" + ", ".join(ada_name(u) for u in USES) + ");")
w("   type Facing is (" + ", ".join(ada_name(f) for f in FACINGS) + ");")
w("")
w(f"   Type_Count : constant := {len(types)};")
w(f"   Empty_Land : constant := {EMPTY};  --  the empty-land placeholder, outside the table")
w("   subtype Type_Id is Integer_32 range 0 .. Empty_Land;")
w("   subtype Listed_Type is Type_Id range 0 .. Type_Count - 1;")
w("")
names = set()
for i, t in enumerate(type_ids):
    n = "T_" + ada_name(t)
    assert n not in names, n
    names.add(n)
    w(f"   {n} : constant := {i};")
w("")
w("   Type_Class : constant array (Type_Id) of Building_Class :=")
w("     [" + wrap([ada_name(t["cls"]) for t in types] + ["Empty"], 6).lstrip() + "];")
w("")
w("   No_Weight : constant := -1;  --  no weight given for the district")
w("   type Weight_Row is array (District) of Integer_32;")
w("   Type_Weight : constant array (Listed_Type) of Weight_Row :=")
rows = []
for t in types:
    rows.append("[" + ", ".join(str(x if x is not None else -1) for x in t["weight"]) + "]")
w("     [" + wrap(rows, 6).lstrip() + "];")
w("")
w("   Type_Recruits : constant array (Type_Id) of Boolean :=")
w("     [" + wrap(["True" if t["recruit"] else "False" for t in types] + ["False"], 6).lstrip() + "];")
w("   Type_Special : constant array (Type_Id) of Boolean :=")
w("     [" + wrap(["True" if t["special"] else "False" for t in types] + ["False"], 6).lstrip() + "];")
w("   Type_Storeys : constant array (Type_Id) of Integer_32 :=")
w("     [" + wrap([str(int(t["storeys"])) for t in types] + ["0"], 6).lstrip() + "];")
w("")
kinds = data["kinds"]
w(f"   Kind_Count : constant := {len(kinds)};")
w("   subtype Kind_Id is Integer_32 range 0 .. Kind_Count - 1;")
w("   No_Kind : constant := -1;")
for field, name in [("group", "Kind_Group"), ("capacity", "Kind_Capacity"), ("capacity_max", "Kind_Capacity_Max"),
                    ("lv_min", "Kind_Lv_Min"), ("lv_max", "Kind_Lv_Max"), ("size", "Kind_Size")]:
    w(f"   {name} : constant array (Kind_Id) of Integer_32 :=")
    w("     [" + wrap([str(int(k[field])) for k in kinds], 6).lstrip() + "];")
w("   Kind_Type : constant array (Kind_Id) of Type_Id :=")
w("     [" + wrap([str(tindex[k["type"]]) for k in kinds], 6).lstrip() + "];")
g = data["kind_groups"]
w("   Group_Start : constant array (Integer_32 range 0 .. 7) of Integer_32 :=")
w("     [" + ", ".join(str(x) for x in g["start"]) + "];")
w("   Group_Count : constant array (Integer_32 range 0 .. 7) of Integer_32 :=")
w("     [" + ", ".join(str(x) for x in g["count"]) + "];")
w("")
trades = data["trades"]
w(f"   Trade_Count : constant := {len(trades)};")
w("   subtype Trade_Id is Integer_32 range 0 .. Trade_Count - 1;")
w("   Trade_Type : constant array (Trade_Id) of Listed_Type :=")
w("     [" + wrap([str(tindex[t["id"]]) for t in trades], 6).lstrip() + "];")
w("   Trade_Family : constant array (Trade_Id) of Plot_Use :=")
w("     [" + wrap([ada_name(t["family"]) for t in trades], 6).lstrip() + "];")
w("   Trade_Upmarket : constant array (Trade_Id) of Boolean :=")
w("     [" + wrap(["True" if t["upmarket"] else "False" for t in trades], 6).lstrip() + "];")
w("")
mods = data["modules"]
plots = [p for m in mods for p in m["plots"]]
for p in plots:
    for k in ("x", "y", "w", "h"):
        assert p[k] == int(p[k]), p
w(f"   Module_Count : constant := {len(mods)};")
w("   subtype Module_Id is Integer_32 range 0 .. Module_Count - 1;")
for i, m in enumerate(mods):
    w(f"   M_{'_'.join(x.capitalize() for x in m['id'].split('-'))} : constant := {i};")
w("   Module_Width : constant array (Module_Id) of Integer_32 :=")
w("     [" + ", ".join(str(m["width"]) for m in mods) + "];")
w("   Module_Depth : constant array (Module_Id) of Integer_32 :=")
w("     [" + ", ".join(str(m["depth"]) for m in mods) + "];")
first, k = [], 0
for m in mods:
    first.append(k)
    k += len(m["plots"])
w("   Plot_First : constant array (Module_Id) of Integer_32 :=")
w("     [" + ", ".join(str(x) for x in first) + "];")
w("   Plot_Count : constant array (Module_Id) of Integer_32 :=")
w("     [" + ", ".join(str(len(m["plots"])) for m in mods) + "];")
w(f"   Plot_Total : constant := {len(plots)};")
w("   subtype Plot_Id is Integer_32 range 0 .. Plot_Total - 1;")
w("   type Plot is record")
w("      Index, X, Y, W, H : Integer_32;")
w("      Face              : Facing;")
w("      Use_Kind          : Plot_Use;")
w("      Vacant            : Boolean;")
w("   end record;")
w("   Plots : constant array (Plot_Id) of Plot :=")
prow = [f"({p['index']}, {int(p['x'])}, {int(p['y'])}, {int(p['w'])}, {int(p['h'])}, "
        f"{ada_name(p['facing'])}, {ada_name(p['use'])}, {'True' if p['vacant'] else 'False'})" for p in plots]
w("     [" + wrap(prow, 6).lstrip() + "];")
w("")
fam = data["families"]
ffirst, flist = [], []
for u in USES:
    ffirst.append(len(flist))
    flist += [tindex[t] for t in fam[u]]
w("   Family_First : constant array (Plot_Use) of Integer_32 :=")
w("     [" + ", ".join(str(x) for x in ffirst) + "];")
w("   Family_Length : constant array (Plot_Use) of Integer_32 :=")
w("     [" + ", ".join(str(len(fam[u])) for u in USES) + "];")
w(f"   Family_Total : constant := {len(flist)};")
w("   Family_Types : constant array (Integer_32 range 0 .. Family_Total - 1) of Listed_Type :=")
w("     [" + wrap([str(x) for x in flist], 6).lstrip() + "];")
w("")
# People (step 4): roles, skills, name pools, hood types, attitudes, rival
# profiles and the hiring places' quotas.
pe = data["people"]
roles = pe["roles"]
w("   --  People (step 4)")
w("   type Role is")
w("     (" + wrap(["R_" + ada_name(r) for r in roles], 6).lstrip() + ");")
w("   type Skill is")
w("     (" + wrap([ada_name(k) for k in pe["skills"]], 6).lstrip() + ");")
w("")
# One text with every name; pools are runs of name numbers.
name_list = []
def pool(names):
    start = len(name_list)
    name_list.extend(names)
    return start, len(names)
pools = {}
for key in ("male_first", "female_first", "surnames", "nicknames", "gang_surnames"):
    pools[key] = pool(pe[key])
her = pe["heritages"]
her_pools = [(pool(h["male"]), pool(h["female"]), pool(h["surnames"])) for h in her]
text = "".join(name_list)
assert all(ord(c) < 128 and c != '"' for c in text)
starts, k = [], 0
for n in name_list:
    starts.append(k)
    k += len(n)
w(f"   Name_Count : constant := {len(name_list)};")
w("   subtype Name_Id is Integer_32 range 0 .. Name_Count - 1;")
w("   No_Name : constant := -1;")
chunks = [text[i:i + 60] for i in range(0, len(text), 60)]
w("   Name_Text : constant String :=")
w("     " + "\n     & ".join('"' + c + '"' for c in chunks) + ";")
w("   Name_Start : constant array (Name_Id) of Integer_32 :=")
w("     [" + wrap([str(x + 1) for x in starts], 6).lstrip() + "];")
w("   Name_Length : constant array (Name_Id) of Integer_32 :=")
w("     [" + wrap([str(len(n)) for n in name_list], 6).lstrip() + "];")
w("   type Name_Pool is (Male_First, Female_First, Surnames, Nicknames, Gang_Surnames);")
w("   Pool_First : constant array (Name_Pool) of Name_Id :=")
w("     [" + ", ".join(str(pools[k][0]) for k in ("male_first", "female_first", "surnames", "nicknames", "gang_surnames")) + "];")
w("   Pool_Length : constant array (Name_Pool) of Integer_32 :=")
w("     [" + ", ".join(str(pools[k][1]) for k in ("male_first", "female_first", "surnames", "nicknames", "gang_surnames")) + "];")
w(f"   Heritage_Count : constant := {len(her)};")
w("   subtype Heritage_Id is Integer_32 range 0 .. Heritage_Count - 1;")
for i, h in enumerate(her):
    w(f"   H_{ada_name(h['id'].replace('-', '_').title().replace('_', ''))} : constant := {i};")
for name, idx in (("Heritage_Male_First", 0), ("Heritage_Male_Count", 0), ("Heritage_Female_First", 1),
                  ("Heritage_Female_Count", 1), ("Heritage_Surname_First", 2), ("Heritage_Surname_Count", 2)):
    part = 0 if name.endswith("First") else 1
    w(f"   {name} : constant array (Heritage_Id) of Integer_32 :=")
    w("     [" + ", ".join(str(hp[idx][part]) for hp in her_pools) + "];")
gs = pe["gang_surnames"]
def heritage_of(surname):
    for i, h in enumerate(her):
        if surname in h["surnames"]:
            return i
    return -1
anglo = [h["id"] for h in her].index("anglo")
w("   --  The heritage of each gang surname (anglo when no heritage has it).")
w("   Gang_Surname_Heritage : constant array (Integer_32 range 0 .. " + str(len(gs) - 1) + ") of Heritage_Id :=")
w("     [" + ", ".join(str(heritage_of(s) if heritage_of(s) >= 0 else anglo) for s in gs) + "];")
pl = pe["player"]
plain = lambda s: "".join(c for c in s.lower() if "a" <= c <= "z")
twin = [i for i, s in enumerate(gs) if plain(s) == plain(pl["last"])]
w("   --  The player's boss (proposed, as 1.2.91's default new game).")
w(f"   Player_First : constant Name_Id := {pools['male_first'][0] + pe['male_first'].index(pl['first'])};")
w(f"   Player_Last : constant Name_Id := {pools['surnames'][0] + pe['surnames'].index(pl['last'])};")
w(f"   Player_Heritage : constant Heritage_Id := {heritage_of(pl['last']) if heritage_of(pl['last']) >= 0 else [h['id'] for h in her].index('italian')};")
w(f"   Player_Gang_Surname : constant Integer_32 := {twin[0] if twin else -1};  --  its twin among the gang surnames")
w("")
ht = pe["hood_types"]
w(f"   Hood_Type_Count : constant := {len(ht)};")
w("   subtype Hood_Type is Integer_32 range 0 .. Hood_Type_Count - 1;")
w("   Hood_Weight : constant array (Hood_Type) of Integer_32 :=")
w("     [" + ", ".join(str(t["weight"]) for t in ht) + "];")
w("   Hood_Business : constant array (Hood_Type) of Boolean :=")
w("     [" + wrap(["True" if t["business"] else "False" for t in ht], 6).lstrip() + "];")
w("   type Skill_Row is array (Skill) of Integer_32;")
w("   Hood_Base : constant array (Hood_Type) of Skill_Row :=")
w("     [" + wrap(["[" + ", ".join(str(r[0]) for r in t["rows"]) + "]" for t in ht], 6).lstrip() + "];")
w("   Hood_Range : constant array (Hood_Type) of Skill_Row :=")
w("     [" + wrap(["[" + ", ".join(str(r[1]) for r in t["rows"]) + "]" for t in ht], 6).lstrip() + "];")
w("")
ac = pe["attitude_classes"]
w("   type Attitude_Class is")
w("     (" + wrap(["A_" + ada_name(c["id"]) for c in ac], 6).lstrip() + ");")
for field, name in (("hostility", "Hostility"), ("fear", "Fear")):
    w(f"   {name}_Base : constant array (Attitude_Class) of Integer_32 :=")
    w("     [" + ", ".join(str(c[field][0]) for c in ac) + "];")
    w(f"   {name}_Range : constant array (Attitude_Class) of Integer_32 :=")
    w("     [" + ", ".join(str(c[field][1]) for c in ac) + "];")
w("   Fear_Adds_Hostility : constant array (Attitude_Class) of Boolean :=")
w("     [" + wrap(["True" if c["fear_adds_hostility"] else "False" for c in ac], 6).lstrip() + "];")
w("   Role_Class : constant array (Role) of Attitude_Class :=")
w("     [" + wrap(["A_" + ada_name(pe["role_class"][r]) for r in roles], 6).lstrip() + "];")
w("")
rp = pe["rival_profiles"]
w(f"   Profile_Count : constant := {len(rp)};")
w("   type Profile_Row is array (Integer_32 range 0 .. 6) of Integer_32;")
w("   Rival_Profile : constant array (Integer_32 range 0 .. Profile_Count - 1) of Profile_Row :=")
w("     [" + wrap(["[" + ", ".join(str(x) for x in r) + "]" for r in rp], 6).lstrip() + "];")
w("")
rq = pe["recruit_quotas"]
w(f"   Quota_Count : constant := {len(rq)};")
w("   subtype Quota_Id is Integer_32 range 0 .. Quota_Count - 1;")
w("   Quota_Type : constant array (Quota_Id) of Listed_Type :=")
w("     [" + ", ".join(str(tindex[q["type"]]) for q in rq) + "];")
w("   Quota_Role : constant array (Quota_Id) of Role :=")
w("     [" + ", ".join("R_" + ada_name(q["role"]) for q in rq) + "];")
w("   Quota_People : constant array (Quota_Id) of Integer_32 :=")
w("     [" + ", ".join(str(q["count"]) for q in rq) + "];")
w("")
w("   Type_Profit : constant array (Type_Id) of Integer_32 :=")
w("     [" + wrap([str(int(t["profit"])) for t in types] + ["0"], 6).lstrip() + "];")
w("")
w("   --  Item 5: price, who is hired there (Role'Pos, -1 nobody), whether a")
w("   --  donation can go there (a church or an orphanage), and how well it")
w("   --  hides an office behind it (cover, hundredths).")
w("   Type_Cost : constant array (Type_Id) of Integer_32 :=")
w("     [" + wrap([str(int(t["cost"])) for t in types] + ["0"], 6).lstrip() + "];")
role_pos = {r: i for i, r in enumerate(roles)}
w("   Type_Recruit_As : constant array (Type_Id) of Integer_32 :=")
w("     [" + wrap([str(role_pos[t["recruit"]]) if t["recruit"] else "-1" for t in types] + ["-1"], 6).lstrip() + "];")
w("   Type_Charity : constant array (Type_Id) of Boolean :=")
w("     [" + wrap(["True" if t["special"] in ("church", "orphanage") and t["cls"] == "charity" else "False" for t in types] + ["False"], 6).lstrip() + "];")
w("   Type_Office_Cover : constant array (Type_Id) of Integer_32 :=")
w("     [" + wrap([str(int(t["office_cover"])) for t in types] + ["60"], 6).lstrip() + "];")
w("")
w("end Hood.Tables;")
(ROOT / "src/hood-tables.ads").write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"src/hood-tables.ads: {len(types)} types, {len(kinds)} kinds, {len(trades)} trades, "
      f"{len(mods)} modules, {len(plots)} plots")

# The page's copy: type names, classes and storeys by type number (the last
# number is empty land), and the place names.
ts = ["// Generated by tools/gen-tables.py from data/tables.json; do not edit.", ""]
ts.append("export const TYPE_NAMES: readonly string[] = " + json.dumps([t["name"] for t in types] + ["Empty land"], ensure_ascii=False) + ";")
ts.append("export const TYPE_IDS: readonly string[] = " + json.dumps([t["id"] for t in types] + ["emptyLand"]) + ";")
ts.append("export const TYPE_CLASSES: readonly string[] = " + json.dumps([t["cls"] for t in types] + ["empty"]) + ";")
ts.append("export const TYPE_COSTS: readonly number[] = " + json.dumps([int(t["cost"]) for t in types] + [0]) + ";")
ts.append("export const PARK_NAMES: readonly string[] = " + json.dumps(data["names"]["parks"], ensure_ascii=False) + ";")
ts.append("export const CHURCH_NAMES: readonly string[] = " + json.dumps(data["names"]["churches"], ensure_ascii=False) + ";")
ts.append("export const STREETS_NS: readonly string[] = " + json.dumps(data["names"]["streets_ns"], ensure_ascii=False) + ";")
ts.append("export const STREETS_EW: readonly string[] = " + json.dumps(data["names"]["streets_ew"], ensure_ascii=False) + ";")
ts.append("export const NAMES: readonly string[] = " + json.dumps(name_list, ensure_ascii=False) + ";")
ts.append("export const ROLES: readonly string[] = " + json.dumps(roles) + ";")
ts.append("export const SKILLS: readonly string[] = " + json.dumps(pe["skills"]) + ";")
ts.append("export const HERITAGES: readonly string[] = " + json.dumps([h["label"] for h in her], ensure_ascii=False) + ";")
(ROOT / "web/src/tables.ts").write_text("\n".join(ts) + "\n", encoding="utf-8")
print(f"web/src/tables.ts: {len(types) + 1} type names")
