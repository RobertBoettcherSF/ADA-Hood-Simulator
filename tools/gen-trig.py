#!/usr/bin/env python3
"""Writes src/hood-trig_table.ads: a quarter-wave sine table.

Angles are 1/1024 of a turn (proposed), so a quarter turn is 256 steps and the
table has 257 entries. Values are sin scaled by 65536 (proposed), rounded to
the nearest whole number. Run once; the output is committed.
"""
import math
from pathlib import Path

STEPS, SCALE = 1024, 65536
QUARTER = STEPS // 4
values = [math.floor(SCALE * math.sin(2 * math.pi * i / STEPS) + 0.5) for i in range(QUARTER + 1)]
values[QUARTER] = SCALE  # sin 90 degrees is exactly 1
rows = []
for k in range(0, len(values), 8):
    rows.append("      " + ", ".join(f"{v:5d}" for v in values[k:k + 8]))
text = f"""--  Generated by tools/gen-trig.py; do not edit.
--  Quarter-wave sine: Quarter (I) = round ({SCALE} * sin (I / {STEPS} turn)).
with Interfaces;

package Hood.Trig_Table with Pure is

   Quarter : constant array (0 .. {QUARTER}) of Interfaces.Integer_32 :=
     [
{(",\n").join(rows)}
     ];

end Hood.Trig_Table;
"""
out = Path(__file__).resolve().parent.parent / "src" / "hood-trig_table.ads"
out.write_text(text)
print(f"Wrote {out} ({len(values)} entries)")
